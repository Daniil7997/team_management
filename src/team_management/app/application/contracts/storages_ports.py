import uuid
from typing import Protocol


class InviteStoreProtocol(Protocol):
    async def startup(self) -> None: ...
    async def shutdown(self) -> None: ...
    async def add_invite_code(
        self, invite_code: uuid.UUID, team_id: str, ttl: int
    ) -> None: ...
    async def get_team_id_from_invite_code(
        self, invite_code: uuid.UUID
    ) -> str | None: ...


class TokensBlacklistProtocol(Protocol):
    async def startup(self) -> None: ...
    async def shutdown(self) -> None: ...
    async def get(self, token: str) -> str | None: ...
    async def set(self, token: str, user_id: str, ttl: int) -> None: ...
